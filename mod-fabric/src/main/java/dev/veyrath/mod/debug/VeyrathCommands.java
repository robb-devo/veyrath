package dev.veyrath.mod.debug;

import com.mojang.brigadier.CommandDispatcher;
import com.mojang.brigadier.arguments.StringArgumentType;
import com.mojang.brigadier.context.CommandContext;
import dev.veyrath.engine.VeyrathWorld;
import dev.veyrath.engine.biome.VBiome;
import dev.veyrath.engine.debug.Locator;
import dev.veyrath.engine.terrain.ColumnInfo;
import dev.veyrath.engine.terrain.TerrainSampler;
import dev.veyrath.mod.VeyrathRuntime;
import dev.veyrath.mod.gen.VeyrathChunkGenerator;
import net.minecraft.commands.CommandSourceStack;
import net.minecraft.commands.Commands;
import net.minecraft.commands.SharedSuggestionProvider;
import net.minecraft.network.chat.Component;
import net.minecraft.world.phys.Vec3;

import java.util.Locale;

/**
 * {@code /veyrath} debug commands (Chapter 01 tooling).
 *
 * <ul>
 *   <li>{@code /veyrath info}: engine data for the column you stand on.</li>
 *   <li>{@code /veyrath locate <target>}: coordinates of a landmark or region.</li>
 *   <li>{@code /veyrath tp <target>}: teleport there (runs vanilla {@code /tp}, so it needs the same
 *       permission: cheats on in singleplayer, operator on a server).</li>
 * </ul>
 *
 * <p>Read-only subcommands need no permission. Teleporting is delegated to vanilla {@code /tp}
 * rather than calling the teleport API directly, which keeps this class independent of
 * version-specific teleport and permission signatures.
 */
public final class VeyrathCommands {
    private VeyrathCommands() {}

    public static void register(CommandDispatcher<CommandSourceStack> dispatcher) {
        dispatcher.register(Commands.literal("veyrath")
                .then(Commands.literal("info").executes(VeyrathCommands::info))
                .then(Commands.literal("locate")
                        .then(Commands.argument("target", StringArgumentType.word())
                                .suggests((ctx, b) -> SharedSuggestionProvider.suggest(Locator.targets(), b))
                                .executes(ctx -> locate(ctx, false))))
                .then(Commands.literal("tp")
                        .then(Commands.argument("target", StringArgumentType.word())
                                .suggests((ctx, b) -> SharedSuggestionProvider.suggest(Locator.targets(), b))
                                .executes(ctx -> locate(ctx, true)))));
    }

    private static VeyrathWorld engineFor(CommandSourceStack source) {
        if (!(source.getLevel().getChunkSource().getGenerator() instanceof VeyrathChunkGenerator)) {
            source.sendFailure(Component.literal("This dimension is not generated by VEYRATH."));
            return null;
        }
        return VeyrathRuntime.world();
    }

    private static int info(CommandContext<CommandSourceStack> ctx) {
        CommandSourceStack source = ctx.getSource();
        VeyrathWorld world = engineFor(source);
        if (world == null) return 0;
        Vec3 p = source.getPosition();
        ColumnInfo c = world.sampleWorld(p.x, p.z, new ColumnInfo(), new TerrainSampler.Scratch());
        VeyrathWorld.Realm realm = world.realmAt(c.x, c.z);
        VBiome biome = realm.biomes().select(c, c.slope);
        String msg = String.format(Locale.ROOT,
                "VEYRATH | %s / %s%n" +
                        "world %.0f %.0f -> engine %.0f %.0f, realm %d,%d%n" +
                        "ground y%.1f, slope %.2f, water %s%n" +
                        "temperature %.2f, moisture %.2f, coast %.0f m, river %s, rift %s",
                c.archetype.displayName, biome.id,
                p.x, p.z, c.x, c.z, realm.atlas().realmX, realm.atlas().realmZ,
                c.ground, c.slope, c.wet() ? String.format(Locale.ROOT, "y%.1f (%s)", c.water, c.waterKind) : "none",
                c.temperature, c.moisture, c.coastDistance,
                c.riverDistance < 1e6 ? String.format(Locale.ROOT, "%.0f m (half width %.0f)", c.riverDistance, c.riverHalfWidth) : "far",
                c.riftDistance < 1e6 ? String.format(Locale.ROOT, "%.0f m, depth %.0f", c.riftDistance, c.riftDepth) : "far");
        source.sendSuccess(() -> Component.literal(msg), false);
        return 1;
    }

    private static int locate(CommandContext<CommandSourceStack> ctx, boolean teleport) {
        CommandSourceStack source = ctx.getSource();
        VeyrathWorld world = engineFor(source);
        if (world == null) return 0;
        String target = StringArgumentType.getString(ctx, "target");
        Vec3 p = source.getPosition();
        int ox = world.originX(), oz = world.originZ();
        Locator.Place place = Locator.find(world, target, p.x + ox, p.z + oz);
        if (place == null) {
            source.sendFailure(Component.literal("No '" + target + "' in this realm. Targets: " + String.join(", ", Locator.targets())));
            return 0;
        }
        double wx = place.x() - ox, wz = place.z() - oz;
        String coords = String.format(Locale.ROOT, "%.1f %.0f %.1f", wx, place.y(), wz);
        source.sendSuccess(() -> Component.literal(place.target() + ": " + coords + " - " + place.description()), false);
        if (teleport) {
            source.getServer().getCommands().performPrefixedCommand(source, "tp @s " + coords);
        }
        return 1;
    }
}
